#!/usr/bin/env node
// Builds ONE self-contained HTML file (no external requests) for Google Apps Script, Canvas, or any web host.
// Usage: node build.js
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'src');
// Engine files run in the browser AND in Node (tests, build). UI files need a real page.
const JS_ENGINE = [
  'util.js', 'seal.js', 'vfs.js', 'samples.js', 'machines.js', 'machines-unix.js', 'terminal.js', 'apps.js', 'awk.js',
  'posix.js', 'posix-cmds.js', 'posix-sys.js', 'unix-cmds.js', 'git.js', 'cmd.js', 'dos.js', 'basic.js',
  'ps-parser.js', 'ps-runtime.js', 'ps-cmdlets.js', 'storage.js', 'lang.js', 'docs.js', 'docs-more.js', 'missions.js', 'missions-more.js',
  'shells.js', 'sandbox.js', 'reference.js', 'lessons.js', 'certtest.js',
];
const JS_UI = ['@TESTBANK', 'ui-core.js', 'ui-home.js', 'ui-reference.js', 'ui-test.js', 'ui-cert.js', 'app.js'];

async function build() {
  // Certification-test question banks: run every reference answer in the sandbox, ship only fingerprints of the results.
  const TX = require('./tests/load.js')();
  const built = await require('./src/banks/build-bank.js')(TX, require('./src/banks/questions.js'));
  if (built.problems.length) { console.error(built.problems.join('\n')); throw new Error('Question bank has problems — fix them before building.'); }
  const bankJson = JSON.stringify(built.bank);
  if (/"(a|ref|answer)":/.test(bankJson)) throw new Error('Answers leaked into the shipped question bank!');
  const bankJs = "(function () {\n  'use strict';\n  // Generated by build.js from src/banks/questions.js — fingerprints only, no answers.\n  window.TX.TESTBANK = " + bankJson + ';\n})();\n';

  const css = fs.readFileSync(path.join(SRC, 'css', 'style.css'), 'utf8');
  const js = JS_ENGINE.concat(JS_UI).map((f) => '// ---- ' + f + ' ----\n' + (f === '@TESTBANK' ? bankJs : fs.readFileSync(path.join(SRC, 'js', f), 'utf8'))).join('\n');
  if (/<\/script/i.test(js)) throw new Error('A source file contains "</script" which would break the inline build.');
  if (/https?:\/\/(fonts\.googleapis|cdn\.jsdelivr|unpkg|cdnjs)/.test(css + js)) throw new Error('The build must not load anything from the internet (school filters).');

  const template = fs.readFileSync(path.join(SRC, 'index.html'), 'utf8');
  const html = template.replace('/*INLINE_CSS*/', () => css).replace('/*INLINE_JS*/', () => js);
  if (html.split('__TX_CLASS_KEY__').length !== 2) throw new Error('The class-key marker must appear exactly once (Code.gs replaces it).');

  fs.mkdirSync(path.join(__dirname, 'dist'), { recursive: true });
  fs.writeFileSync(path.join(__dirname, 'dist', 'index.html'), html);
  writeAppsScript(template, css, JS_ENGINE.concat(JS_UI).map((f) => '// ---- ' + f + ' ----\n' + (f === '@TESTBANK' ? bankJs : fs.readFileSync(path.join(SRC, 'js', f), 'utf8'))));
  const nq = Object.values(built.bank).reduce((a, b) => a + b.length, 0);
  console.log('Built dist/index.html (' + Math.round(html.length / 1024) + ' KB; ' + nq + ' certification-test questions)');
}

// Google Apps Script copes badly with one huge HTML file (the editor can stall or cut off a 1.6 MB paste),
// so the Apps Script copy is split: a small Index page plus Styles and Js1..JsN files, each under ~350 KB,
// stitched together at serve time by Code.gs with the standard include() pattern.
function writeAppsScript(template, css, jsParts) {
  const dir = path.join(__dirname, 'apps-script');
  fs.readdirSync(dir).filter((f) => /^(Index|Styles|Js\d+)\.html$/.test(f)).forEach((f) => fs.unlinkSync(path.join(dir, f)));
  const LIMIT = 350 * 1024;
  const chunks = [];
  let cur = '';
  for (const part of jsParts) {
    if (cur && cur.length + part.length > LIMIT) { chunks.push(cur); cur = ''; }
    cur += part + '\n';
  }
  if (cur) chunks.push(cur);
  const body = template.slice(template.indexOf('<body>') + 6, template.indexOf('<script>')).replace(/\s+$/, '');
  const index = '<!DOCTYPE html>\n<html lang="en">\n<head>\n<base target="_top">\n<meta charset="utf-8">\n<title>TerminalEX</title>\n<style>\n<?!= include(\'Styles\') ?>\n</style>\n</head>\n<body>' + body + '\n' +
    chunks.map((_, i) => `<script>\n<?!= include('Js${i + 1}') ?>\n</script>`).join('\n') + '\n</body>\n</html>\n';
  if (/<\?(?!!= include\('(Styles|Js\d+)'\) \?>)/.test(index)) throw new Error('Apps Script Index has an unexpected <? scriptlet');
  fs.writeFileSync(path.join(dir, 'Index.html'), index);
  fs.writeFileSync(path.join(dir, 'Styles.html'), css);
  chunks.forEach((c, i) => fs.writeFileSync(path.join(dir, `Js${i + 1}.html`), c));
  console.log(`Apps Script: Index.html + Styles.html + ${chunks.map((c, i) => `Js${i + 1}.html (${Math.round(c.length / 1024)} KB)`).join(', ')}`);
}

module.exports = { JS_ENGINE, JS_UI };
if (require.main === module) build().catch((e) => { console.error(e); process.exit(1); });
